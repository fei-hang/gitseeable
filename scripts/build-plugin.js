// 构建 DSH 插件包：把 server 与已构建的 client 产物装配进 dsh-plugin/。
//
// dsh-plugin 自身不参与 npm workspaces（仓库里三个包各自独立安装），
// 所以这里只是"装配"：把 esbuild 打出的单文件服务器 + client/dist 复制进去，
// 让插件目录成为一个可直接 `dsh plugin add ./dsh-plugin` 的自包含包。
const fs = require('fs');
const path = require('path');
const esbuild = require(path.join(__dirname, '..', 'client', 'node_modules', 'esbuild'));

const root = path.join(__dirname, '..');
const pluginRoot = path.join(root, 'dsh-plugin');
const serverOut = path.join(pluginRoot, 'server');
const publicOut = path.join(serverOut, 'public');
const clientDist = path.join(root, 'client', 'dist');

async function main() {
  if (!fs.existsSync(path.join(clientDist, 'index.html'))) {
    console.error('client/dist 不存在 —— 先运行 npm run build:client');
    process.exit(1);
  }

  fs.rmSync(serverOut, { recursive: true, force: true });
  fs.mkdirSync(serverOut, { recursive: true });

  // 单文件 CJS：express / cors / simple-git 一并打进 bundle，
  // 插件因此不依赖宿主 profile 的 node_modules 解析结果。
  // 扩展名必须是 .cjs —— 插件包本身是 "type": "module"。
  // 只打应用本体（app.cjs）：插件由宿主驱动，不需要独立入口的监听逻辑。
  await esbuild.build({
    entryPoints: [path.join(root, 'server', 'app.ts')],
    bundle: true,
    platform: 'node',
    target: 'node20',
    format: 'cjs',
    outfile: path.join(serverOut, 'app.cjs'),
    logLevel: 'info',
    banner: { js: '// Generated by scripts/build-plugin.js — do not edit.' },
  });

  fs.cpSync(clientDist, publicOut, { recursive: true });

  console.log(`plugin assembled → ${pluginRoot}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
